import type { ProviderSettings, ProviderUpdate } from './projects'
import type { Entry } from './contracts'
import type { ProjectLensReference } from './project-lens'

export const explanationPurposes = ['tutor', 'project-lens'] as const
export const explanationActions = ['hint', 'concept', 'debug', 'walkthrough', 'review-attempt', 'quiz',
  'understand', 'architecture', 'health', 'teach-project', 'next-steps', 'ask-codebase'] as const
export type ExplanationPurpose = typeof explanationPurposes[number]
export type ExplanationAction = typeof explanationActions[number]

export interface ReviewedSource {
  id: string
  label: string
  origin: 'saved-file' | 'editor-buffer' | 'lesson' | 'diagnostic' | 'structure'
  revision: string
  startLine: number
  endLine: number
  text: string
}

export interface ExplanationInput {
  purpose: ExplanationPurpose
  action: ExplanationAction
  question: string
  sources: readonly ReviewedSource[]
}

/** Renderer requests identify context; main assembles and validates reviewed sources. */
export interface ExplanationRequest {
  purpose: ExplanationPurpose
  action: ExplanationAction
  question: string
  lesson?: { packId: string; lessonId: string }
  code?: { path?: string; label: string; text: string; version: number }
  diagnostic?: string
  project?: { root: string; refs: ProjectLensReference[] }
}

export interface ExplanationReview {
  token: string
  provider: ProviderSettings
  bodyBytes: number
  expiresAt: number
  sources: ReviewedSource[]
  exclusions: string[]
  question: string
  purpose: ExplanationPurpose
  action: ExplanationAction
}

export interface ExplanationCitation {
  sourceId: string
  startLine: number
  endLine: number
}

export interface ExplanationReply {
  /** Issued by Ion's review session, never generated by the provider. */
  token: string
  summary: string
  sections: Array<{
    kind: 'observed' | 'inferred' | 'unknown' | 'suggestion'
    title: string
    text: string
    citations: ExplanationCitation[]
  }>
  questions: string[]
  recommendations: Array<{
    id: string
    title: string
    description: string
    acceptance: string[]
    dependsOn: string[]
    citations: ExplanationCitation[]
  }>
}

export type ExplanationContent = Omit<ExplanationReply, 'token'>

export interface ExplanationOpenResult {
  entry?: Entry
  range?: { startLine: number; startColumn: number; endLine: number; endColumn: number }
  lesson?: { packId: string; lessonId: string }
  label?: string
  text?: string
}

export interface ExplanationBridge {
  /** Local provider metadata only; explicitly opens the optional AI-pane lease. */
  provider(): Promise<ProviderSettings>
  configure(value: ProviderUpdate): Promise<ProviderSettings>
  review(request: ExplanationRequest): Promise<ExplanationReview>
  send(token: string): Promise<ExplanationReply | null>
  cancel(): Promise<void>
  openCitation(token: string, sourceId: string, range: { startLine: number; endLine: number }): Promise<ExplanationOpenResult>
}
