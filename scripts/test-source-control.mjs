import assert from 'node:assert/strict'
import { mkdir, readFile, writeFile } from 'node:fs/promises'
import { basename, join } from 'node:path'
import { artifact, atPath, close, editorShows, launch, openFolder, openFromExplorer, stubDialogs, withScratch } from './desktop-harness.mjs'
import { developmentFixture, git, waitForChildren } from './development-workflow-fixtures.mjs'

const rootKey = process.platform === 'darwin' ? 'Meta' : 'Control'
await withScratch('git-desktop', async (scratch) => {
  const project = await developmentFixture(join(scratch, 'repo with spaces'))
  const other = await developmentFixture(join(scratch, 'unrelated repository'))
  const otherBefore = await git(other.directory, 'status', '--porcelain=v2')
  const profile = join(scratch, 'profile')
  await mkdir(profile)
  await writeFile(join(profile, 'preferences.json'), JSON.stringify({ version: 1, settings: { autoSave: false } }))
  const session = await launch(await artifact('dist'), profile)
  const { page, app } = session
  try {
    await page.context().setOffline(true)
    await stubDialogs(app, { folder: project.directory })
    await openFolder(page, project)
    await openFromExplorer(page, project.changed, 'changed line')
    assert.equal(await page.evaluate(() => performance.getEntriesByType('resource').some(({ name }) => /SourceControl/.test(name))), false)
    await assert.rejects(page.evaluate((root) => window.ion.sourceControl.status(root), other.directory), /Open the repository folder/)
    await page.getByTestId('toggle-source-control').click()
    const panel = page.getByTestId('source-control')
    const trust = panel.getByTestId('git-trust')
    await trust.click()
    await trust.waitFor()
    assert.equal(await panel.getByTestId('git-branch').count(), 0)
    await stubDialogs(app, { folder: project.directory, allowGit: true })
    await trust.click()
    const working = panel.getByTestId('git-working')
    const staged = panel.getByTestId('git-staged')
    const change = (group, path) => group.getByTestId('git-open-diff').and(group.locator(`[data-git-path=${JSON.stringify(path)}]`))
    const file = basename(project.changed)
    await change(working, file).waitFor()
    assert.match(await panel.getByTestId('git-branch').innerText(), /main/)
    assert.equal(await change(working, basename(project.ignored)).count(), 0)
    await change(working, basename(project.untracked)).waitFor()
    await change(staged, basename(project.deleted)).waitFor()
    await change(staged, basename(project.renamedTo)).waitFor()
    await atPath(page, 'explorer-row', project.changed).locator('[data-git-status="M"]').waitFor()

    const originalEditor = page.getByTestId('editor').locator('.monaco-editor')
    await originalEditor.evaluate(node => { node.dataset.originalEditor = 'true' })
    await originalEditor.locator('.view-line').first().click()
    await page.keyboard.press(process.platform === 'darwin' ? 'Meta+ArrowRight' : 'End')
    await page.keyboard.insertText(' UNSAVED')
    await editorShows(page, 'UNSAVED')
    await change(working, file).click()
    const diff = page.getByTestId('git-diff')
    await diff.locator('.monaco-diff-editor').waitFor()
    await diff.getByText(/unsaved/i).waitFor()
    const sides = diff.locator('.monaco-diff-editor .view-lines')
    assert.match(await sides.first().innerText(), /second\sline/)
    assert.match(await sides.last().innerText(), /changed\sline/)
    assert.doesNotMatch(await sides.last().innerText(), /UNSAVED/)
    if (process.env.ION_SOURCE_CONTROL_SCREENSHOT) await page.screenshot({ path: process.env.ION_SOURCE_CONTROL_SCREENSHOT })
    await diff.getByRole('button', { name: /Inline/i }).click()
    await diff.getByRole('button', { name: /next change/i }).click()
    await diff.getByRole('button', { name: /close diff/i }).click()
    await diff.waitFor({ state: 'detached' })
    assert.equal(await originalEditor.getAttribute('data-original-editor'), 'true')
    await editorShows(page, 'UNSAVED')
    assert.equal(await panel.getByRole('button', { name: 'Stage ' + file }).isDisabled(), true)
    await originalEditor.locator('.view-line').first().click()
    await page.keyboard.press(rootKey + '+z')
    await page.waitForFunction(() => !document.querySelector('[data-testid="editor"] .view-lines').textContent.includes('UNSAVED'))
    assert.equal(await readFile(project.changed, 'utf8'), project.modified)
    await atPath(page, 'close-tab', project.changed).click()
    const unsaved = page.getByRole('dialog', { name: 'Unsaved changes' })
    await Promise.race([unsaved.waitFor(), atPath(page, 'tab', project.changed).waitFor({ state: 'detached' })])
    if (await unsaved.isVisible()) await unsaved.getByRole('button', { name: 'Discard', exact: true }).click()

    await panel.getByRole('button', { name: 'Stage ' + file }).click()
    await change(staged, file).waitFor()
    assert.equal(await git(project.directory, 'show', ':' + file), project.modified)
    await change(staged, file).click()
    await diff.locator('.monaco-diff-editor').waitFor()
    await diff.getByRole('button', { name: /close diff/i }).click()
    await panel.getByRole('button', { name: 'Unstage ' + file }).click()
    await change(working, file).waitFor()
    assert.equal(await git(project.directory, 'show', ':' + file), project.original)
    await panel.getByRole('button', { name: 'Stage ' + file }).click()
    await change(staged, file).waitFor()
    await panel.getByTestId('git-commit-message').fill('Save reviewed changes')
    await panel.getByTestId('git-commit').click()
    await change(staged, file).waitFor({ state: 'detached' })
    assert.equal((await git(project.directory, 'log', '-1', '--format=%s')).trim(), 'Save reviewed changes')
    assert.equal(await git(other.directory, 'status', '--porcelain=v2'), otherBefore)
    assert.equal(await readFile(project.changed, 'utf8'), project.modified)
    for (let cycle = 0; cycle < 4; cycle++) {
      await page.getByTestId('toggle-source-control').click()
      await panel.waitFor({ state: 'detached' })
      await page.getByTestId('toggle-source-control').click()
      await panel.getByTestId('git-branch').waitFor()
    }
    await page.getByTestId('toggle-source-control').click()
    await waitForChildren(session, children => children.every(({ name }) => !/^git(?:\.exe)?$/i.test(name)), 'Git subprocess remained after close.')
    assert.equal(await page.locator('.monaco-diff-editor').count(), 0)
    assert.deepEqual(session.requests, [])
    assert.deepEqual(session.errors, [])
    console.log('PASS native Git status, ignored files, diff state and navigation, stage/unstage, commit, workspace isolation and cleanup')
  } catch (error) {
    console.error('Source Control fixture failed', error, session.errors)
    throw error
  } finally { await close(session) }
})
